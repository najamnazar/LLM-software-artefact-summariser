"""evaluate_pr_summaries.py

Compute BERTScore and TF-IDF cosine similarity for PR summaries generated by
pr_llm_summariser.py.

Workflow
--------
1. Read per-model JSONL summary files from the output directory.
2. Batch-compute BERTScore (roberta-large, one call per model label) and
   TF-IDF cosine similarity (sklearn) for every sample.
3. Rewrite each JSONL file with a ``"metrics"`` key added to every record.
4. Write aggregated dataset-level averages to ``results.json``.

Mirrors the evaluation approach used in DPS_LLM's evaluate_summaries.py:
- BERTScore uses the functional API with ``lang='en'`` (roberta-large), batching
  all pairs for a model into one forward pass so the model loads once.
- Cosine similarity uses sklearn TfidfVectorizer + cosine_similarity; no model
  download or load required.

Usage:
    python evaluate_pr_summaries.py [MODEL ...] [options]

    positional:
      MODEL               One or more of: GPT, QWEN, CLAUDE, MISTRAL, ALL
                          Default: ALL

    optional:
      --output DIR        Directory containing JSONL summary files
                          Default: <PR_LLM>/output/
      --limit N           Only evaluate the first N entries per model
      --bertscore-lang S  Language for BERTScore ('en' selects roberta-large)
                          Default: en
      --log-level LEVEL   DEBUG, INFO, WARNING, ERROR  (default: INFO)

:author: Najam Nazar
:version: 1.0.0
:date: 2026-06-22
:license: MIT
"""

